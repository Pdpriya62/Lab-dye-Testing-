"""
Synthetic dataset generator - Multi-Sensor IoT Framework for Textile Lab-Dip Testing

SYNTHETIC DATA: generated by simulation, NOT measured. Label it as synthetic in any report.

Sensors modelled (matching the project hardware):
  - DS18B20  : dye-bath temperature (12-bit, 0.0625 C steps, ~+-0.5 C)
  - DHT22    : ambient temperature + humidity (0.1 steps, ~+-0.5 C, ~+-2 %RH)
               set DHT_MODEL = "DHT11" for integer readings, ~+-2 C, ~+-5 %RH
  - BH1750   : light intensity inside the light box (1 lux steps, ~+-20 %)
  - TCS34725 : colour sensor (raw R,G,B,Clear counts, plus derived Lab / sRGB)

Output files:
  sensor_readings.csv : time series, one row per 30 s per sample
  sample_results.csv  : one row per sample (recipe, target vs measured colour, dE, pass/fail)

Assumptions anchored to published literature:
  - Colour acceptance threshold: CIEDE2000 <= 1.0 (textile industry values of 0.8-1.0 are the usual limit)
  - Dye-bath set points: reactive on cellulosics ~60 C, acid on nylon ~90 C, low-temp disperse on polyester ~98 C
  - Lower-than-set dye-bath temperature -> less dye uptake -> lighter, less saturated shade
"""
import numpy as np
import pandas as pd
from datetime import datetime, timedelta

SEED = 42
N_SAMPLES = 60
DHT_MODEL = "DHT22"          # or "DHT11"
INTERVAL_S = 30
LUX_TARGET = 1200            # light-box illuminance target (lux)
PASS_LIMIT = 1.0             # CIEDE2000 limit

rng = np.random.default_rng(SEED)

# ---------- colour maths ----------
def lab_to_xyz(L, a, b):
    fy = (L + 16) / 116
    fx = fy + a / 500
    fz = fy - b / 200
    f = lambda t: t ** 3 if t ** 3 > 0.008856 else (t - 16 / 116) / 7.787
    return 0.95047 * f(fx), 1.0 * f(fy), 1.08883 * f(fz)

def lab_to_lin_rgb(L, a, b):
    X, Y, Z = lab_to_xyz(L, a, b)
    M = np.array([[3.2406, -1.5372, -0.4986],
                  [-0.9689, 1.8758, 0.0415],
                  [0.0557, -0.2040, 1.0570]])
    return np.clip(M @ np.array([X, Y, Z]), 0, 1)

def lin_to_srgb8(lin):
    g = np.where(lin <= 0.0031308, 12.92 * lin, 1.055 * np.power(lin, 1 / 2.4) - 0.055)
    return np.clip(np.round(g * 255), 0, 255).astype(int)

def de76(l1, l2):
    return float(np.sqrt(sum((x - y) ** 2 for x, y in zip(l1, l2))))

def de2000(l1, l2):
    L1, a1, b1 = l1
    L2, a2, b2 = l2
    rad, deg = np.radians, np.degrees
    C1, C2 = np.hypot(a1, b1), np.hypot(a2, b2)
    Cb = (C1 + C2) / 2
    G = 0.5 * (1 - np.sqrt(Cb ** 7 / (Cb ** 7 + 25 ** 7)))
    a1p, a2p = (1 + G) * a1, (1 + G) * a2
    C1p, C2p = np.hypot(a1p, b1), np.hypot(a2p, b2)
    h1p = deg(np.arctan2(b1, a1p)) % 360
    h2p = deg(np.arctan2(b2, a2p)) % 360
    dLp, dCp = L2 - L1, C2p - C1p
    if C1p * C2p == 0:
        dh = 0
    else:
        dh = h2p - h1p
        if dh > 180:
            dh -= 360
        elif dh < -180:
            dh += 360
    dHp = 2 * np.sqrt(C1p * C2p) * np.sin(rad(dh / 2))
    Lbp, Cbp = (L1 + L2) / 2, (C1p + C2p) / 2
    if C1p * C2p == 0:
        hbp = h1p + h2p
    elif abs(h1p - h2p) <= 180:
        hbp = (h1p + h2p) / 2
    elif h1p + h2p < 360:
        hbp = (h1p + h2p + 360) / 2
    else:
        hbp = (h1p + h2p - 360) / 2
    T = (1 - 0.17 * np.cos(rad(hbp - 30)) + 0.24 * np.cos(rad(2 * hbp))
         + 0.32 * np.cos(rad(3 * hbp + 6)) - 0.20 * np.cos(rad(4 * hbp - 63)))
    dth = 30 * np.exp(-((hbp - 275) / 25) ** 2)
    Rc = 2 * np.sqrt(Cbp ** 7 / (Cbp ** 7 + 25 ** 7))
    Sl = 1 + 0.015 * (Lbp - 50) ** 2 / np.sqrt(20 + (Lbp - 50) ** 2)
    Sc, Sh = 1 + 0.045 * Cbp, 1 + 0.015 * Cbp * T
    Rt = -np.sin(rad(2 * dth)) * Rc
    return float(np.sqrt((dLp / Sl) ** 2 + (dCp / Sc) ** 2 + (dHp / Sh) ** 2
                         + Rt * (dCp / Sc) * (dHp / Sh)))

# ---------- sensor models ----------
def dht_read(t, rh):
    if DHT_MODEL == "DHT22":
        return round(t + rng.normal(0, 0.2), 1), round(float(np.clip(rh + rng.normal(0, 1.0), 0, 100)), 1)
    return float(round(t + rng.normal(0, 0.8))), float(round(np.clip(rh + rng.normal(0, 2.5), 20, 90)))

def ds18b20(t):
    return round(round((t + rng.normal(0, 0.1)) / 0.0625) * 0.0625, 4)

# ---------- recipe options ----------
SHADES = {  # name: (L, a, b) target
    "Navy": (25, 2, -22), "Royal Blue": (35, 15, -52), "Red": (45, 62, 40),
    "Maroon": (28, 40, 18), "Yellow": (85, -3, 82), "Orange": (65, 45, 65),
    "Bottle Green": (30, -30, 12), "Leaf Green": (52, -45, 28), "Teal": (45, -30, -10),
    "Pink": (72, 35, 5), "Purple": (35, 40, -35), "Brown": (35, 15, 25),
    "Olive": (50, -10, 45), "Charcoal": (28, 0, -2), "Beige": (76, 5, 20),
    "Sky Blue": (70, -8, -25),
}
SYSTEMS = [  # fabric, dye class, set point C, weight
    ("Cotton", "Reactive", 60, 0.40),
    ("Viscose", "Reactive", 60, 0.20),
    ("Nylon", "Acid", 90, 0.15),
    ("Polyester", "Disperse", 98, 0.25),
]

# ---------- ambient model (Bengaluru, Oct) ----------
def ambient_at(day_T, day_RH, ts):
    h = ts.hour + ts.minute / 60
    wave = np.sin(np.pi * np.clip(h - 8, 0, 12) / 12)
    return day_T + 2.0 * wave, day_RH - 9.0 * wave

# ---------- main ----------
days = [datetime(2026, 10, 19) + timedelta(days=d) for d in (0, 1, 2, 3, 4, 7, 8)]  # Mon-Fri, Mon-Tue
per_day = int(np.ceil(N_SAMPLES / len(days)))
day_env = {d: (rng.normal(26, 1.2), float(np.clip(rng.normal(62, 8), 40, 85))) for d in days}

readings, results = [], []
sid = 0
shade_names = list(SHADES)
sys_p = np.array([s[3] for s in SYSTEMS]) / sum(s[3] for s in SYSTEMS)

for day in days:
    t_cursor = day.replace(hour=9, minute=30)
    day_T, day_RH = day_env[day]
    for _ in range(per_day):
        if sid >= N_SAMPLES:
            break
        sid += 1
        sample_id = f"LD-{sid:03d}"
        fabric, dye_class, sp, _w = SYSTEMS[rng.choice(len(SYSTEMS), p=sys_p)]
        shade = shade_names[rng.integers(len(shade_names))]
        Lt, at, bt = SHADES[shade]
        conc = float(np.clip(0.05 + (100 - Lt) / 100 * 3.6 + rng.normal(0, 0.25), 0.05, 4.0))
        hold_min = int(rng.integers(25, 41))
        ramp_min = max(6, int((sp - day_T) / rng.uniform(4.5, 6.5)))
        cool_min = 4

        # fault scenario for the dye bath
        fault = rng.choice(["none", "dip", "sustained_low", "sustained_high"], p=[0.55, 0.20, 0.17, 0.08])
        bias = rng.normal(0, 0.35)
        if fault == "sustained_low":
            bias -= rng.uniform(1.5, 3.2)
        if fault == "sustained_high":
            bias += rng.uniform(1.5, 2.5)
        dip_start = rng.integers(2, max(3, hold_min - 8))
        dip_len = rng.integers(3, 9)
        dip_depth = rng.uniform(2.5, 6.0)

        # lighting scenario inside the light box
        lux_base = LUX_TARGET * (1 + rng.normal(0, 0.05))
        leak = rng.random() < 0.2
        leak_start = rng.integers(5, max(6, hold_min))
        leak_len = rng.integers(3, 10)
        leak_gain = rng.uniform(1.15, 1.45)

        n_steps = int((ramp_min + hold_min + cool_min) * 60 / INTERVAL_S)
        amb_T_noise = amb_H_noise = 0.0
        sample_rows = []
        for k in range(n_steps):
            ts = t_cursor + timedelta(seconds=k * INTERVAL_S)
            el_min = k * INTERVAL_S / 60
            if el_min < ramp_min:
                phase = "ramp"
                x = el_min / ramp_min
                true_T = day_T + (sp + bias - day_T) * (1 - np.exp(-3.2 * x)) / (1 - np.exp(-3.2))
            elif el_min < ramp_min + hold_min:
                phase = "hold"
                m = el_min - ramp_min
                true_T = sp + bias + 0.6 * np.sin(2 * np.pi * m / 2.5) + rng.normal(0, 0.15)
                if fault == "dip" and dip_start <= m < dip_start + dip_len:
                    true_T -= dip_depth * np.sin(np.pi * (m - dip_start) / dip_len)
            else:
                phase = "cool"
                c = el_min - ramp_min - hold_min
                true_T = max(40, (sp + bias) - 12 * c) + rng.normal(0, 0.2)

            ambT, ambH = ambient_at(day_T, day_RH, ts)
            amb_T_noise = 0.9 * amb_T_noise + rng.normal(0, 0.08)
            amb_H_noise = 0.9 * amb_H_noise + rng.normal(0, 0.4)
            dT, dH = dht_read(ambT + amb_T_noise + 0.004 * (true_T - day_T), ambH + amb_H_noise)

            lux = lux_base * (1 + rng.normal(0, 0.015))
            if leak and leak_start <= el_min - ramp_min < leak_start + leak_len:
                lux *= leak_gain
            sample_rows.append({
                "timestamp": ts.strftime("%Y-%m-%d %H:%M:%S"),
                "sample_id": sample_id,
                "elapsed_s": k * INTERVAL_S,
                "phase": phase,
                "setpoint_c": sp,
                "dyebath_temp_c": ds18b20(true_T),
                "ambient_temp_c": dT,
                "humidity_pct": dH,
                "light_lux": int(max(0, round(lux))),
                "data_source": "synthetic",
            })
        readings.extend(sample_rows)
        sr = pd.DataFrame(sample_rows)
        hold = sr[sr.phase == "hold"]
        under = float(np.maximum(sp - hold.dyebath_temp_c, 0).mean())
        over = float(np.maximum(hold.dyebath_temp_c - sp, 0).mean())

        # measurement after cooling + ~35 min drying
        meas_ts = t_cursor + timedelta(minutes=ramp_min + hold_min + cool_min + 35)
        mT, mH = ambient_at(day_T, day_RH, meas_ts)
        mT, mH = dht_read(mT + rng.normal(0, 0.2), mH + rng.normal(0, 1.0))
        lux_m = int(round(lux_base * (1 + rng.normal(0, 0.03))))
        if rng.random() < 0.12:
            lux_m = int(round(lux_m * rng.uniform(1.18, 1.4)))   # careless measurement, light leak
        lux_dev = (lux_m - LUX_TARGET) / LUX_TARGET

        f = 0.012 * under
        t_L = 0.35 * under - 0.12 * over
        l_L = 4.0 * lux_dev
        h_L = -0.025 * (mH - 60)
        Lm = Lt + t_L + l_L + h_L + rng.normal(0, 0.22)
        am = at * (1 - f + 0.004 * over) + rng.normal(0, 0.2)
        bm = bt * (1 - f + 0.004 * over) + rng.normal(0, 0.2)
        Lm = float(np.clip(Lm, 1, 99))

        d76 = de76((Lt, at, bt), (Lm, am, bm))
        d00 = de2000((Lt, at, bt), (Lm, am, bm))
        Ct = np.hypot(at, bt)
        contrib = {"dye_bath_temperature": abs(t_L) + Ct * f,
                   "lighting": abs(l_L),
                   "humidity": abs(h_L)}
        driver = max(contrib, key=contrib.get)
        if contrib[driver] < 0.3:
            driver = "none (random variation)"

        lin = lab_to_lin_rgb(Lm, am, bm)
        scale = 20000 * (lux_m / LUX_TARGET)
        raw = np.clip(lin * scale * (1 + rng.normal(0, 0.01, 3)), 0, 65535)
        clear = int(min(65535, raw.sum() * 1.1 + 600 + rng.normal(0, 40)))
        r8, g8, b8 = lin_to_srgb8(lin)

        results.append({
            "sample_id": sample_id,
            "session_start": t_cursor.strftime("%Y-%m-%d %H:%M:%S"),
            "measured_at": meas_ts.strftime("%Y-%m-%d %H:%M:%S"),
            "fabric": fabric, "dye_class": dye_class, "shade_name": shade,
            "dye_conc_pct_owf": round(conc, 2), "liquor_ratio": "1:20",
            "setpoint_c": sp, "hold_time_min": hold_min,
            "target_L": Lt, "target_a": at, "target_b": bt,
            "measured_L": round(Lm, 2), "measured_a": round(am, 2), "measured_b": round(bm, 2),
            "tcs_raw_R": int(raw[0]), "tcs_raw_G": int(raw[1]), "tcs_raw_B": int(raw[2]), "tcs_raw_clear": clear,
            "rgb_R": int(r8), "rgb_G": int(g8), "rgb_B": int(b8),
            "delta_E_76": round(d76, 2), "delta_E_2000": round(d00, 2),
            "result": "PASS" if d00 <= PASS_LIMIT else "FAIL",
            "hold_mean_temp_c": round(float(hold.dyebath_temp_c.mean()), 2),
            "hold_min_temp_c": round(float(hold.dyebath_temp_c.min()), 2),
            "hold_max_temp_c": round(float(hold.dyebath_temp_c.max()), 2),
            "hold_temp_std_c": round(float(hold.dyebath_temp_c.std()), 2),
            "mean_ambient_temp_c": round(float(sr.ambient_temp_c.mean()), 1),
            "mean_humidity_pct": round(float(sr.humidity_pct.mean()), 1),
            "mean_light_lux": int(round(sr.light_lux.mean())),
            "ambient_temp_at_measure_c": mT, "humidity_at_measure_pct": mH, "light_lux_at_measure": lux_m,
            "main_deviation_driver": driver,
            "data_source": "synthetic",
        })
        t_cursor += timedelta(minutes=ramp_min + hold_min + cool_min + 8)

pd.DataFrame(readings).to_csv("sensor_readings.csv", index=False)
pd.DataFrame(results).to_csv("sample_results.csv", index=False)
print("done:", len(readings), "reading rows,", len(results), "samples")
